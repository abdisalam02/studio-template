#!/usr/bin/env node
// Generates docs/ARCHITECTURE.md: route -> file map, big-file outlines, sources of truth.
// Run: npm run arch      Re-run after adding, moving or splitting files.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

const SRC = existsSync('src') ? 'src' : '.';
const APP = existsSync(join(SRC, 'app')) ? join(SRC, 'app') : 'app';
const BIG = 500; // lines: files above this get an outline
const SKIP = new Set(['node_modules', '.next', '.git', 'dist', 'build']);
const posix = (p) => p.split(sep).join('/');
const lines = (f) => readFileSync(f, 'utf8').split(/\r?\n/);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    if (SKIP.has(n)) continue;
    const p = join(dir, n);
    statSync(p).isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
}

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith('@/')) base = join(SRC, spec.slice(2));
  else if (spec.startsWith('.')) base = join(dirname(from), spec);
  else return null;
  for (const c of [base, `${base}.tsx`, `${base}.ts`, join(base, 'index.tsx'), join(base, 'index.ts')]) {
    if (existsSync(c) && statSync(c).isFile()) return c;
  }
  return null;
}

// Routes
const routes = walk(APP)
  .filter((f) => /(^|[\\/])(page\.(tsx|jsx|ts|js)|route\.(ts|js))$/.test(f))
  .map((f) => {
    const rel = posix(relative(APP, f)).replace(/\/?(page|route)\.\w+$/, '');
    const url = '/' + rel.split('/').filter((s) => s && !/^\(.*\)$/.test(s)).join('/');
    const src = lines(f);
    const imports = [...src.join('\n').matchAll(/from\s+['"]([^'"]+)['"]/g)]
      .map((m) => resolveImport(f, m[1]))
      .filter(Boolean)
      .filter((p) => !/[\\/]ui[\\/]/.test(p))
      .slice(0, 3);
    return { url, f: posix(f), n: src.length, imports, api: /route\.\w+$/.test(f) };
  })
  .sort((a, b) => a.url.localeCompare(b.url));

const out = [];
out.push('# ARCHITECTURE.md (generated by `npm run arch`; do not edit by hand)', '');
out.push('Read this before searching. Open files by line range. Never read a "Big file" whole.', '');
out.push('## Routes', '| URL | Entry (lines) | UI lives in (lines) |', '|---|---|---|');
for (const r of routes) {
  const ui = r.imports.length
    ? r.imports.map((p) => `${posix(p)} (${lines(p).length})`).join('<br>')
    : r.api ? 'API handler' : 'self-contained';
  out.push(`| ${r.url} | ${r.f} (${r.n}) | ${ui} |`);
}

// Big files
const big = walk(SRC)
  .filter((f) => /\.(ts|tsx)$/.test(f))
  .map((f) => ({ f, src: lines(f) }))
  .filter((x) => x.src.length > BIG)
  .sort((a, b) => b.src.length - a.src.length);

out.push('', `## Big files (over ${BIG} lines: use these ranges)`);
if (!big.length) out.push('None.');
for (const { f, src } of big) {
  const syms = [];
  src.forEach((l, i) => {
    const m = l.match(/^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?|const|class|interface|type)\s+([A-Za-z_$][\w$]*)/);
    if (m) syms.push({ name: m[1], start: i + 1 });
  });
  out.push(`### ${posix(f)} (${src.length} lines)`);
  if (syms.length < 3) {
    out.push('Mostly data or one block. Split it or add an index before editing.');
    continue;
  }
  const spans = syms.map((s, i) => ({ ...s, end: i + 1 < syms.length ? syms[i + 1].start - 1 : src.length }));
  const shown = spans.filter((s) => s.end - s.start + 1 >= 20).slice(0, 30).map((s) => `${s.name} L${s.start}-${s.end}`);
  out.push(shown.length ? shown.join('; ') : 'No large symbols. Split by section before editing.');
}

// Sources of truth
out.push('', '## Sources of truth');
for (const f of ['src/config/legal.ts', 'docs/DESIGN.md', 'docs/PRICING.md', 'docs/ASSETS.md', 'docs/INSPO_WORKFLOW.md', 'docs/STATE.md', 'GEMINI.md']) {
  if (existsSync(f)) out.push(`- ${f}`);
}

writeFileSync('docs/ARCHITECTURE.md', out.join('\n') + '\n');
console.log(`docs/ARCHITECTURE.md written: ${routes.length} routes, ${big.length} big file(s).`);
